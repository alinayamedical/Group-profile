// download_fonts.js — Downloads Raleway + Cairo from Google Fonts,
// embeds them as base64 @font-face into export_png.js, then exits.
// Run once: node download_fonts.js

const https = require('https');
const fs    = require('fs');
const path  = require('path');

// Chrome UA so Google Fonts returns WOFF2 (supported by Puppeteer's Chromium)
const UA = 'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/120.0.0.0 Safari/537.36';

function get(url, binary = false) {
  return new Promise((resolve, reject) => {
    https.get(url, { headers: { 'User-Agent': UA } }, res => {
      if (res.statusCode === 301 || res.statusCode === 302) {
        return resolve(get(res.headers.location, binary));
      }
      const chunks = [];
      res.on('data', c => chunks.push(Buffer.from(c)));
      res.on('end', () => {
        const buf = Buffer.concat(chunks);
        resolve(binary ? buf : buf.toString('utf8'));
      });
      res.on('error', reject);
    }).on('error', reject);
  });
}

async function main() {
  // ── 1. Fetch font CSS ────────────────────────────────────────────────────
  const API = 'https://fonts.googleapis.com/css2?family=Raleway:wght@500;700&family=Cairo:wght@600&display=swap';
  console.log('\n── Downloading font definitions ────────────────────────────');
  console.log(`   ${API}\n`);

  const css = await get(API);

  // ── 2. Parse all @font-face blocks ──────────────────────────────────────
  const faceRe = /@font-face\s*\{([^}]+)\}/g;
  const faces  = [];
  let m;

  while ((m = faceRe.exec(css)) !== null) {
    const block   = m[1];
    const family  = (block.match(/font-family:\s*['"]?([^;'"]+)/) || [])[1]?.trim();
    const weight  = (block.match(/font-weight:\s*(\d+)/)           || [])[1]?.trim();
    const url     = (block.match(/url\(([^)]+)\)/)                 || [])[1]?.trim();
    const fmt     = (block.match(/format\(['"]?(\w+)/)             || [])[1]?.trim() || 'woff2';
    const unicode = (block.match(/unicode-range:\s*([^;]+)/)       || [])[1]?.trim();

    if (family && weight && url) faces.push({ family, weight, url, fmt, unicode });
  }

  // Keep only the weights we actually use in the logos
  const NEEDED = [
    { family: 'Raleway', weight: '700' },
    { family: 'Raleway', weight: '500' },
    { family: 'Cairo',   weight: '600' },
  ];

  const selected = faces.filter(f =>
    NEEDED.some(n => n.family === f.family && n.weight === f.weight)
  );

  console.log(`   Found ${faces.length} font-face blocks → keeping ${selected.length} for these weights:`);
  NEEDED.forEach(n => console.log(`   • ${n.family} ${n.weight}`));
  console.log('');

  // ── 3. Download each WOFF2 and base64-encode ─────────────────────────────
  const embedded = [];

  for (const face of selected) {
    const subset = face.unicode
      ? (face.unicode.includes('0600') ? 'arabic'
        : face.unicode.includes('0100') ? 'latin-ext'
        : 'latin')
      : 'latin';

    process.stdout.write(`   Downloading ${face.family} ${face.weight} [${subset}] … `);
    const buf = await get(face.url, true);
    const b64 = buf.toString('base64');
    console.log(`${Math.round(buf.length / 1024)} KB`);

    embedded.push({ ...face, b64, subset });
  }

  // ── 4. Build embedded @font-face CSS ─────────────────────────────────────
  let fontCss = '<style>\n';
  for (const f of embedded) {
    fontCss += `  @font-face {\n`;
    fontCss += `    font-family: '${f.family}';\n`;
    fontCss += `    font-style: normal;\n`;
    fontCss += `    font-weight: ${f.weight};\n`;
    fontCss += `    src: url('data:font/woff2;base64,${f.b64}') format('woff2');\n`;
    if (f.unicode) fontCss += `    unicode-range: ${f.unicode};\n`;
    fontCss += `  }\n`;
  }
  fontCss += '</style>';

  // ── 5. Patch export_png.js ────────────────────────────────────────────────
  const exportPath = path.join(__dirname, 'export_png.js');
  let src = fs.readFileSync(exportPath, 'utf8');

  src = src.replace(
    /\/\/ Font styles.*?(?=\n\/\/ ── Export manifest)/s,
    `// Fonts embedded as base64 WOFF2 — generated by download_fonts.js\nconst FONTS = \`\n${fontCss}\n\`;\n\n`
  );

  fs.writeFileSync(exportPath, src, 'utf8');

  console.log(`\n   ✓ Patched export_png.js with ${embedded.length} embedded font faces`);
  console.log('   ✓ Raleway 500 / 700 (latin + latin-ext)');
  console.log('   ✓ Cairo 600 (arabic + latin)');
  console.log('\n── Running export now ──────────────────────────────────────\n');
}

main().catch(err => {
  console.error('\nError:', err.message);
  process.exit(1);
});
